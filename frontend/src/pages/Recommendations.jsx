import { useParams } from 'react-router-dom'
import { api } from '../api/client'
import { AsyncSection, Badge, PageHeader, useAsync } from '../components/ui'
import { AIStatus } from '../components/AIBadge'

const P_TONE = { 1: 'danger', 2: 'warn', 3: 'info' }

export default function Recommendations() {
  const { projectId } = useParams()
  const state = useAsync(() => api.recommendations(projectId), [projectId])

  return (
    <>
      <PageHeader title="Recommendations"
                  subtitle="Strategic actions generated by the AI reasoning layer from your analytics" />
      <AsyncSection state={state} empty="Analysis not finished yet.">
        {(a) => (
          <div className="space-y-4">
            <AIStatus status={a.status} provider={a.provider} model={a.model} error={a.error} />

            {a.status === 'ok' && a.priority_actions?.length > 0 && (
              <div className="card-pad">
                <div className="h-title mb-3">Priority Actions</div>
                <ol className="space-y-2">
                  {a.priority_actions.map((p, i) => (
                    <li key={i} className="flex gap-3 text-sm text-slate-200">
                      <span className="w-6 h-6 shrink-0 rounded-full bg-accent/20 text-accent text-xs flex items-center justify-center font-semibold">{i + 1}</span>
                      {p}
                    </li>
                  ))}
                </ol>
              </div>
            )}

            {(a.deterministic_recommendations || []).length > 0 && (
              <div className="card-pad">
                <div className="h-title mb-1">Rule-derived Recommendations</div>
                <div className="text-xs text-slate-500 mb-3">
                  Deterministic — each one is triggered by a measured finding, never by AI narrative
                </div>
                <div className="space-y-3">
                  {a.deterministic_recommendations.map((r) => (
                    <div key={r.id} className="flex items-start gap-3 flex-wrap">
                      <Badge tone={P_TONE[r.priority] || 'info'}>P{r.priority}</Badge>
                      <div className="flex-1 min-w-[16rem]">
                        <div className="font-medium text-slate-100">{r.action}</div>
                        <div className="text-xs text-slate-500 mt-0.5">Trigger: {r.trigger}</div>
                        {r.evidence_ids?.length > 0 && (
                          <div className="flex gap-1.5 flex-wrap mt-1">
                            {r.evidence_ids.map((e) => (
                              <span key={e} className="text-[11px] font-mono bg-surface px-1.5 py-0.5 rounded border border-surface-border text-slate-500">{e}</span>
                            ))}
                          </div>
                        )}
                      </div>
                    </div>
                  ))}
                </div>
              </div>
            )}

            {a.status === 'ok' && (a.recommendations || []).map((r, i) => (
              <div key={i} className="card-pad">
                <div className="flex items-start gap-3 flex-wrap">
                  <Badge tone={P_TONE[r.priority] || 'info'}>{r.priority ? `P${r.priority}` : 'rec'}</Badge>
                  {r.verification === 'unverified' && <Badge tone="warn">unverified</Badge>}
                  <div className="flex-1 min-w-[16rem]">
                    <div className="font-medium text-slate-100">{r.action}</div>
                    {r.rationale && <div className="text-sm text-slate-500 mt-1">Why: {r.rationale}</div>}
                    {r.evidence_ids?.length > 0 && (
                      <div className="flex gap-1.5 flex-wrap mt-1">
                        {r.evidence_ids.map((e) => (
                          <span key={e} className="text-[11px] font-mono bg-surface px-1.5 py-0.5 rounded border border-surface-border text-slate-500">{e}</span>
                        ))}
                      </div>
                    )}
                  </div>
                </div>
                <div className="grid grid-cols-2 md:grid-cols-4 gap-3 mt-4 text-sm">
                  <div><div className="h-sub">Expected impact</div><div className="text-slate-300 mt-0.5">{r.expected_impact || '—'}</div></div>
                  <div><div className="h-sub">Difficulty</div><div className="text-slate-300 mt-0.5 capitalize">{r.difficulty || '—'}</div></div>
                  <div><div className="h-sub">Owner</div><div className="text-slate-300 mt-0.5">{r.owner || '—'}</div></div>
                  <div><div className="h-sub">Timeline</div><div className="text-slate-300 mt-0.5">{r.timeline || '—'}</div></div>
                </div>
              </div>
            ))}
          </div>
        )}
      </AsyncSection>
    </>
  )
}
